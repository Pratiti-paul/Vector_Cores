"""
tests/test_assembler.py – Integration tests for the full assembler pipeline.

Tests the assemble() function end-to-end: source text → list of 16-bit words.
Expected values are hand-calculated independently (not generated by encoder).

Also includes:
  - Regression test: basic_alu.asm output must match the existing program.hex
  - Label resolution (forward + backward)
  - Error propagation
  - Output format verification
"""

import pytest
from pathlib import Path
from assembler.assembler import assemble, words_to_hex
from assembler.validator import AssemblerError


# ---------------------------------------------------------------------------
# Individual instruction encoding via full pipeline
# ---------------------------------------------------------------------------

class TestFullPipelineEncoding:
    """
    Each test feeds a minimal one-instruction program and verifies the word
    at index 0, plus padding at indices 1–15.
    """

    def _word(self, source: str) -> int:
        words = assemble(source)
        return words[0]

    def test_load(self):
        """LOAD R3, [2] → 0x1C80"""
        assert self._word("LOAD R3, [2]") == 0x1C80

    def test_store(self):
        """STORE R1, [2] → 0x2480"""
        assert self._word("STORE R1, [2]") == 0x2480

    def test_add(self):
        """ADD R1, R1, R2 → 0x3580"""
        assert self._word("ADD R1, R1, R2") == 0x3580

    def test_sub(self):
        """SUB R1, R1, R2 → 0x4580"""
        assert self._word("SUB R1, R1, R2") == 0x4580

    def test_addi_positive(self):
        """ADDI R1, R0, 5 → 0x5405"""
        assert self._word("ADDI R1, R0, 5") == 0x5405

    def test_addi_negative(self):
        """ADDI R0, R0, -1 → 0x50FF"""
        assert self._word("ADDI R0, R0, -1") == 0x50FF

    def test_addi_min_imm(self):
        """ADDI R1, R0, -128 → 0x5480"""
        assert self._word("ADDI R1, R0, -128") == 0x5480

    def test_addi_max_imm(self):
        """ADDI R1, R0, 127 → 0x547F"""
        assert self._word("ADDI R1, R0, 127") == 0x547F

    def test_beq_numeric_offset(self):
        """BEQ R1, R2, 2 at addr 0 → 0x6602"""
        assert self._word("BEQ R1, R2, 2") == 0x6602

    def test_jump(self):
        """JUMP 5 → 0x7005"""
        assert self._word("JUMP 5") == 0x7005

    def test_and(self):
        """AND R3, R1, R2 → 0x8D80"""
        assert self._word("AND R3, R1, R2") == 0x8D80

    def test_or(self):
        """OR R3, R1, R2 → 0x9D80"""
        assert self._word("OR R3, R1, R2") == 0x9D80

    def test_xor(self):
        """XOR R3, R1, R2 → 0xAD80"""
        assert self._word("XOR R3, R1, R2") == 0xAD80

    def test_halt(self):
        """HALT → 0xF000"""
        assert self._word("HALT") == 0xF000


# ---------------------------------------------------------------------------
# Output format
# ---------------------------------------------------------------------------

class TestOutputFormat:

    def test_always_16_words(self):
        """assemble() must always return exactly 16 words."""
        for src in ["HALT", "ADDI R1, R0, 5\nHALT", ""]:
            words = assemble(src)
            assert len(words) == 16

    def test_padding_is_halt(self):
        """Unused slots must be F000."""
        words = assemble("ADDI R1, R0, 5\nHALT")
        assert all(w == 0xF000 for w in words[2:])

    def test_all_words_16bit(self):
        """Every word must fit in 16 bits."""
        words = assemble("ADD R1, R2, R3\nHALT")
        assert all(0 <= w <= 0xFFFF for w in words)

    def test_hex_string_format(self):
        """words_to_hex must produce 4-char uppercase lines."""
        words = assemble("HALT")
        hex_str = words_to_hex(words)
        lines = hex_str.strip().splitlines()
        assert len(lines) == 16
        for line in lines:
            assert len(line) == 4
            assert line == line.upper()

    def test_hex_no_prefix(self):
        """No '0x' prefix in output."""
        words = assemble("HALT")
        assert "0x" not in words_to_hex(words)
        assert "0X" not in words_to_hex(words)


