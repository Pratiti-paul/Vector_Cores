# Error cases
# ---------------------------------------------------------------------------

class TestErrorCases:

    def test_unknown_instruction(self):
        with pytest.raises(AssemblerError, match="Unknown instruction"):
            assemble("MUL R1, R2, R3")

    def test_invalid_register(self):
        with pytest.raises(AssemblerError, match="Invalid register"):
            assemble("ADD R4, R1, R2")

    def test_invalid_register_r5(self):
        with pytest.raises(AssemblerError, match="Invalid register"):
            assemble("ADDI R5, R0, 1")

    def test_imm_too_large(self):
        with pytest.raises(AssemblerError, match="out of signed 8-bit range"):
            assemble("ADDI R1, R0, 128")

    def test_imm_too_small(self):
        with pytest.raises(AssemblerError, match="out of signed 8-bit range"):
            assemble("ADDI R1, R0, -129")

    def test_dmem_addr_too_large(self):
        with pytest.raises(AssemblerError, match="out of range"):
            assemble("LOAD R1, [16]")

    def test_jump_addr_too_large(self):
        with pytest.raises(AssemblerError, match="out of range"):
            assemble("JUMP 16")

    def test_too_many_operands(self):
        with pytest.raises(AssemblerError, match="expects"):
            assemble("HALT R0")

    def test_too_few_operands(self):
        with pytest.raises(AssemblerError, match="expects"):
            assemble("ADD R1, R2")

    def test_undefined_label(self):
        with pytest.raises(AssemblerError, match="Undefined label|Cannot parse"):
            assemble("JUMP UNDEFINED_LABEL")

    def test_duplicate_label(self):
        with pytest.raises(AssemblerError, match="Duplicate label"):
            assemble("LOOP: HALT\nLOOP: ADDI R1, R0, 1")

    def test_program_too_large(self):
        # 17 HALT instructions
        src = "\n".join(["HALT"] * 17)
        with pytest.raises(AssemblerError, match="too large"):
            assemble(src)

    def test_exactly_16_instructions_ok(self):
        src = "\n".join(["HALT"] * 16)
        words = assemble(src)
        assert len(words) == 16

    def test_missing_brackets_load(self):
        with pytest.raises(AssemblerError, match="syntax"):
            assemble("LOAD R1, 2")

    def test_error_reports_line_number(self):
        src = "ADDI R1, R0, 5\n# comment\nADD R4, R1, R2"
        with pytest.raises(AssemblerError, match="line 3"):
            assemble(src)


# ---------------------------------------------------------------------------
# Regression test: basic_alu.asm vs existing program.hex
# ---------------------------------------------------------------------------

class TestRegression:

    EXPECTED_WORDS = [
        0x5405,  # ADDI R1, R0, 5
        0x5803,  # ADDI R2, R0, 3
        0x3580,  # ADD  R1, R1, R2
        0x2480,  # STORE R1, [2]
        0x4580,  # SUB  R1, R1, R2
        0x1C80,  # LOAD R3, [2]
        0x5F01,  # ADDI R3, R3, 1
        0xF000,  # HALT
        # padding
        0xF000, 0xF000, 0xF000, 0xF000,
        0xF000, 0xF000, 0xF000, 0xF000,
    ]

    def test_basic_alu_sample_matches_expected(self):
        """
        Assemble basic_alu.asm and compare with hand-verified expected values.
        These values also match the existing program.hex in the repository.
        """
        src_path = Path(__file__).parent.parent / "assembler/samples/basic_alu.asm"
        source = src_path.read_text(encoding="utf-8")
        words = assemble(source)
        assert words == self.EXPECTED_WORDS

    def test_basic_alu_matches_repo_program_hex(self):
        """
        The assembler's output for basic_alu.asm must match the existing
        program.hex file in the repository root (the reference encoding).
        """
        repo_root = Path(__file__).parent.parent
        hex_path = repo_root / "program.hex"
        repo_lines = hex_path.read_text(encoding="utf-8").strip().splitlines()

        src_path = repo_root / "assembler/samples/basic_alu.asm"
        source = src_path.read_text(encoding="utf-8")
        words = assemble(source)
        asm_lines = words_to_hex(words).strip().splitlines()

        assert asm_lines == repo_lines

    def test_branch_jump_sample_assembles(self):
        """branch_jump.asm must assemble without errors."""
        src_path = Path(__file__).parent.parent / "assembler/samples/branch_jump.asm"
        source = src_path.read_text(encoding="utf-8")
        words = assemble(source)
        # Hand-calculated encodings:
        # ADDI R1, R0, 0 → rd=01 rs=00 imm=00000000 → 0x5400
        # ADDI R2, R0, 3 → rd=10 rs=00 imm=00000011 → 0x5803
        # BEQ  R1, R2, DONE  → DONE=addr5, BEQ at addr2, offset=5-(2+1)=+2
        #   rs=01 rt=10 offset=00000010 → 0x6602
        # ADDI R1, R1, 1 → rd=01 rs=01 imm=00000001 → 0x5501
        # JUMP LOOP(=addr2) → 0x7002
        # HALT → 0xF000
        assert words[0] == 0x5400  # ADDI R1, R0, 0
        assert words[1] == 0x5803  # ADDI R2, R0, 3
        assert words[2] == 0x6602  # BEQ  R1, R2, DONE (offset=+2)
        assert words[3] == 0x5501  # ADDI R1, R1, 1  (rd=01,rs=01,imm=1)
        assert words[4] == 0x7002  # JUMP LOOP (absolute addr 2)
        assert words[5] == 0xF000  # HALT

    def test_logical_ops_sample_assembles(self):
        """logical_ops.asm must produce correct AND/OR/XOR encodings."""
        src_path = Path(__file__).parent.parent / "assembler/samples/logical_ops.asm"
        source = src_path.read_text(encoding="utf-8")
        words = assemble(source)
        assert words[0] == 0x540C  # ADDI R1, R0, 12
        assert words[1] == 0x580A  # ADDI R2, R0, 10
        assert words[2] == 0x8D80  # AND  R3, R1, R2
        assert words[3] == 0x9D80  # OR   R3, R1, R2
        assert words[4] == 0xAD80  # XOR  R3, R1, R2
        assert words[5] == 0xF000  # HALT
