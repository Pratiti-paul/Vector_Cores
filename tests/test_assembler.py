# Label resolution
# ---------------------------------------------------------------------------

class TestLabelResolution:

    def test_backward_label_beq(self):
        """
        BEQ at addr 1 targeting LOOP at addr 0:
          offset = 0 − (1 + 1) = −2
        BEQ R0, R0, -2:
          0110 00 00 1111_1110 = 0x60FE
        """
        src = "LOOP: ADDI R1, R0, 0\nBEQ R0, R0, LOOP\nHALT"
        words = assemble(src)
        assert words[1] == 0x60FE

    def test_forward_label_beq(self):
        """
        BEQ at addr 0 targeting DONE at addr 2:
          offset = 2 − (0 + 1) = 1
        BEQ R1, R2, 1:
          0110 01 10 0000_0001 = 0x6601
        """
        src = "BEQ R1, R2, DONE\nADDI R1, R1, 1\nDONE: HALT"
        words = assemble(src)
        assert words[0] == 0x6601

    def test_jump_label(self):
        """JUMP to LOOP at address 1 → 0x7001"""
        src = "ADDI R1, R0, 0\nLOOP: ADDI R1, R1, 1\nJUMP LOOP\nHALT"
        words = assemble(src)
        assert words[2] == 0x7001

    def test_jump_forward_label(self):
        """
        JUMP at addr 0, END is at addr 2 → 0x7002
        """
        src = "JUMP END\nADDI R1, R0, 1\nEND: HALT"
        words = assemble(src)
        assert words[0] == 0x7002

    def test_label_on_own_line(self):
        """Label on own line points to NEXT instruction.
        ADDI=addr0, LOOP:=label→addr1(HALT), HALT=addr1, JUMP=addr2
        JUMP LOOP → JUMP 1 → 0x7001 at words[2]
        """
        src = "ADDI R1, R0, 0\nLOOP:\nHALT\nJUMP LOOP"
        words = assemble(src)
        # JUMP is at instruction address 2 (words[2]); target=LOOP=addr1
        assert words[2] == 0x7001


